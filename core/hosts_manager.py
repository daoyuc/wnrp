# -*- coding: utf-8 -*-
"""hosts 文件管理：把站点域名自动映射到本机（127.0.0.1）。

定位：
- Windows：%SystemRoot%\\System32\\drivers\\etc\\hosts；
- macOS / Linux：/etc/hosts。

写入策略：
- 追加带 phpvm 标记的块，便于人工识别 / 清理；
- 已指向目标 IP 的域名跳过，不产生重复条目；
- 已指向其它 IP 的域名不做覆盖（避免误改用户手写映射），只提示；
- 普通追加失败（无写权限）时按平台走提权写入：
    Windows → PowerShell Start-Process -Verb RunAs（弹 UAC）；
    macOS   → osascript `do shell script ... with administrator privileges`（弹系统授权框）；
    其它 Linux → 返回错误提示，交用户手动处理。
"""
import base64
import os
import re
import sys

from . import process_utils as pu
from .config import IS_WIN
from .i18n import t

MANAGED_TAG = "phpvm-managed"
DEFAULT_IP = "127.0.0.1"

# IPv4 / IPv6 地址（用于把每行首个 token 识别成 IP）
_RE_IP = re.compile(r"^[0-9.]+$|^[0-9a-fA-F:]+$")


def hosts_path() -> str:
    """返回当前平台 hosts 文件绝对路径。"""
    if IS_WIN:
        return os.path.join(
            os.environ.get("SystemRoot", r"C:\Windows"),
            "System32", "drivers", "etc", "hosts",
        )
    return "/etc/hosts"


def read_text() -> str:
    """读取 hosts 全文；失败抛 OSError。"""
    with open(hosts_path(), "r", encoding="utf-8", errors="replace") as f:
        return f.read()


def parse_mapping(text: str) -> dict[str, str]:
    """解析 hosts 文本 → {小写域名: ip}（跳过注释行；多个域名逐行收集）。"""
    mapping: dict[str, str] = {}
    for raw in text.splitlines():
        content = raw.split("#", 1)[0].strip()
        if not content:
            continue
        parts = content.split()
        if not parts:
            continue
        if _RE_IP.match(parts[0]):
            ip, names = parts[0], parts[1:]
        else:
            # 罕见顺序（hostname 在前）：视首个 token 为域名，不识别 IP
            ip, names = "", parts
        for name in names:
            if name:
                mapping.setdefault(name.lower(), ip)
    return mapping


def get_domain_ip(domain: str) -> str | None:
    """返回域名当前在 hosts 中映射的 IP；未配置返回 None。"""
    domain = domain.strip().lower()
    if not domain:
        return None
    try:
        text = read_text()
    except OSError:
        return None
    return parse_mapping(text).get(domain)


def mapping_for_domains(domains: list[str]) -> dict[str, str | None]:
    """批量查询多个域名的 hosts 映射（一次读取）。返回 {域名: ip | None}。"""
    out: dict[str, str | None] = {}
    keys = {d.strip().lower() for d in domains if d and d.strip()}
    if not keys:
        return out
    try:
        mapping = parse_mapping(read_text())
    except OSError:
        return {k: None for k in keys}
    for k in keys:
        out[k] = mapping.get(k)
    return out


