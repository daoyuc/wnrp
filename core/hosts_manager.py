# 写入
# --------------------------------------------------------------------------- #
def _block_text(domains: list[str], ip: str = DEFAULT_IP) -> str:
    """把待追加域名组织成带标记的文本块（不保证结尾换行）。"""
    line = f"{ip} {' '.join(domains)}    # {MANAGED_TAG}: auto site mapping"
    return (
        f"# >>> {MANAGED_TAG} (auto generated by phpvm, do not edit) >>>\n"
        f"{line}\n"
        f"# <<< {MANAGED_TAG} <<<\n"
    )


def ensure_entries(domains: list[str], ip: str = DEFAULT_IP) -> dict:
    """确保域名已映射到本机 ip。返回结果字典：
    {ok, elevated, added[], already[], conflict[], message}
    """
    todo: list[str] = []
    already: list[str] = []
    conflict: list[str] = []
    try:
        mapping = parse_mapping(read_text())
    except OSError as e:
        return {"ok": False, "elevated": False, "added": [], "already": [],
                "conflict": [], "message": t("读取 hosts 失败：{err}", err=e)}
    for d in domains:
        d = (d or "").strip().lower()
        if not d:
            continue
        cur = mapping.get(d)
        if cur is None:
            todo.append(d)
        elif cur == ip:
            already.append(d)
        else:
            conflict.append(d)

    if not todo:
        detail = "、".join(already) or "—"
        if conflict:
            msg = t("hosts 无需修改（已指向 {ip}：{detail}）；以下域名指向其它 IP，未改动：{others}",
                    ip=ip, detail=detail, others=", ".join(conflict))
        else:
            msg = t("hosts 无需修改（已指向 {ip}：{detail}）", ip=ip, detail=detail)
        return {"ok": True, "elevated": False, "added": [], "already": already,
                "conflict": conflict, "message": msg}

    block = _block_text(todo, ip)
    path = hosts_path()
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            existed = f.read()
        if existed and not existed.endswith("\n"):
            block = "\n" + block
        with open(path, "a", encoding="ascii", errors="replace") as f:
            f.write(block)
        return {"ok": True, "elevated": False, "added": todo, "already": already,
                "conflict": conflict,
                "message": t("已写入 hosts：{ip} {doms}", ip=ip, doms=" ".join(todo))}
    except PermissionError:
        return _write_elevated(block, todo, already, conflict)
    except OSError as e:
        return {"ok": False, "elevated": False, "added": [], "already": already,
                "conflict": conflict, "message": t("写入 hosts 失败：{err}", err=e)}


def _write_elevated(block: str, todo: list[str], already: list[str],
                    conflict: list[str]) -> dict:
    """普通追加无权限时，按平台提权写入。"""
    path = hosts_path()
    b64 = base64.b64encode(block.encode("utf-8")).decode("ascii")
    if IS_WIN:
        ps = (
            "param([string]$b64)\n"
            "$h = Join-Path $env:SystemRoot 'System32\\drivers\\etc\\hosts'\n"
            "$t = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($b64))\n"
            "$t = $t -replace \"`n\",\"`r`n\"\n"
            "Add-Content -LiteralPath $h -Value $t -Encoding ASCII\n"
        )
        child = base64.b64encode(ps.encode("utf-16-le")).decode("ascii")
        cmd = [
            "powershell", "-NoProfile", "-NonInteractive", "-Command",
            "Start-Process -FilePath powershell -Verb RunAs -Wait "
            "-ArgumentList '-NoProfile','-EncodedCommand','%s'" % child,
        ]
        code, out, err = pu.run_cmd(cmd, timeout=120)
        if code == 0:
            return {"ok": True, "elevated": True, "added": todo, "already": already,
                    "conflict": conflict,
                    "message": t("已通过管理员授权写入 hosts：{doms}", doms=" ".join(todo))}
        return {"ok": False, "elevated": True, "added": [], "already": already,
                "conflict": conflict,
                "message": t("写入 hosts 需要管理员权限（授权被取消或失败）。\n"
                             "可手动打开 hosts 文件追加：127.0.0.1 {doms}", doms=" ".join(todo))}
    if sys.platform == "darwin":
        cmd = [
            "osascript", "-e",
            f'do shell script "echo {b64} | base64 -D >> {path}" '
            "with administrator privileges",
        ]
        code, out, err = pu.run_cmd(cmd, timeout=180)
        if code == 0:
            return {"ok": True, "elevated": True, "added": todo, "already": already,
                    "conflict": conflict,
                    "message": t("已通过系统授权写入 hosts：{doms}", doms=" ".join(todo))}
        return {"ok": False, "elevated": True, "added": [], "already": already,
                "conflict": conflict,
                "message": t("写入 /etc/hosts 需要管理员授权（已取消或失败：{err}）。\n"
                             "可手动编辑 /etc/hosts 追加：127.0.0.1 {doms}",
                             err=err.strip() or t("无输出"), doms=" ".join(todo))}
    # 其它 Linux：无密码弹框手段，交用户手动处理
    return {"ok": False, "elevated": False, "added": [], "already": already,
            "conflict": conflict,
            "message": t("写入 /etc/hosts 需要 root 权限。请在终端手动执行：\n"
                         "sudo sh -c 'echo \"127.0.0.1 {doms}\" >> /etc/hosts'",
                         doms=" ".join(todo))}
